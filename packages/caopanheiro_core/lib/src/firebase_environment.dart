import 'package:cloud_functions/cloud_functions.dart';
import 'package:firebase_core/firebase_core.dart';

// Apps without their own firebase_core dependency type their staging options.
export 'package:firebase_core/firebase_core.dart' show FirebaseOptions;

/// Where the apps connect, chosen at build time with
/// `--dart-define=CAOPANHEIRO_ENV=local|staging`. Without the definition the
/// build is local: existing builds and tests keep using the emulators.
enum FirebaseEnvironment { local, staging }

const localFirebaseProject = 'demo-caopanheiro-local';

/// Real Firebase projects the apps may use outside the emulators, the same
/// closed list as backend/src/runtime.js.
const allowedFirebaseProjects = {'caopanheiro-staging-fly'};
const localEmulatorHosts = {'127.0.0.1', 'localhost', '10.0.2.2'};

FirebaseEnvironment parseFirebaseEnvironment(String value) => switch (value) {
  'local' => FirebaseEnvironment.local,
  'staging' => FirebaseEnvironment.staging,
  _ => throw const FormatException(
    'Ambiente do Firebase desconhecido: use local ou staging.',
  ),
};

/// Environment of this build.
FirebaseEnvironment get buildFirebaseEnvironment => parseFirebaseEnvironment(
  const String.fromEnvironment('CAOPANHEIRO_ENV', defaultValue: 'local'),
);

/// [note], preceded by a space, only in a local build, whose e-mails stay in
/// the emulators; empty in a staging build, whose e-mails are really sent.
String localBuildNote(String note) =>
    buildFirebaseEnvironment == FirebaseEnvironment.local ? ' $note' : '';

/// Refuses a connection outside the environment of the build: local accepts
/// only the emulator hosts with the demo project; staging accepts only a
/// project of [allowedFirebaseProjects] and never an emulator host.
void requireFirebaseTarget(
  FirebaseEnvironment environment, {
  required String projectId,
  String? host,
}) {
  switch (environment) {
    case FirebaseEnvironment.local:
      if (!localEmulatorHosts.contains(host) ||
          projectId != localFirebaseProject) {
        throw const FormatException('Transporte aceita somente Firebase local.');
      }
    case FirebaseEnvironment.staging:
      if (host != null || !allowedFirebaseProjects.contains(projectId)) {
        throw const FormatException('Projeto Firebase não autorizado.');
      }
  }
}

/// Starts the default app of a staging build with the options generated by
/// `flutterfire configure` for the app. An emulator host given to a staging
/// build is refused, as the backend refuses an emulator with a real project.
Future<FirebaseApp> initializeStagingApp(
  FirebaseOptions Function()? options, {
  String emulatorHost = const String.fromEnvironment('FIREBASE_EMULATOR_HOST'),
}) {
  if (options == null) {
    throw const FormatException(
      'Configuração do Firebase de staging ausente neste aplicativo.',
    );
  }
  final settings = options();
  requireFirebaseTarget(
    FirebaseEnvironment.staging,
    projectId: settings.projectId,
    host: emulatorHost.isEmpty ? null : emulatorHost,
  );
  return Firebase.initializeApp(options: settings);
}

/// Servers that may answer the calls of a staging build instead of the Cloud
/// Functions of the project (branch dev-banco-fly, backend/server); the same
/// name is the app of backend/fly.toml.
const allowedApiHosts = {'caopanheiro-staging-api.fly.dev'};

/// Server of the calls, chosen at build time with
/// `--dart-define=CAOPANHEIRO_API_URL=...`. Without it, null: the calls go to
/// the Cloud Functions of the project or to the functions emulator. A staging
/// build accepts only https on a host of [allowedApiHosts]; a local build only
/// http on an emulator host with its port, where `node server/main.js`
/// serves beside the emulators.
Uri? parseApiServer(FirebaseEnvironment environment, String value) {
  if (value.isEmpty) return null;
  final uri = Uri.tryParse(value);
  if (uri == null ||
      uri.userInfo.isNotEmpty ||
      uri.hasQuery ||
      uri.hasFragment ||
      (uri.path.isNotEmpty && uri.path != '/')) {
    throw const FormatException('Servidor das chamadas não autorizado.');
  }
  final allowed = switch (environment) {
    FirebaseEnvironment.local =>
      uri.scheme == 'http' &&
          localEmulatorHosts.contains(uri.host) &&
          uri.hasPort,
    FirebaseEnvironment.staging =>
      uri.scheme == 'https' &&
          allowedApiHosts.contains(uri.host) &&
          (!uri.hasPort || uri.port == 443),
  };
  if (!allowed) {
    throw const FormatException('Servidor das chamadas não autorizado.');
  }
  return Uri(
    scheme: uri.scheme,
    host: uri.host,
    port: uri.hasPort ? uri.port : null,
  );
}

/// Server of the calls of this build; refuses an address outside the rules of
/// [parseApiServer].
Uri? get buildApiServer => parseApiServer(
  buildFirebaseEnvironment,
  const String.fromEnvironment('CAOPANHEIRO_API_URL'),
);

/// The callable [name] on [server], or on [functions] when there is none.
/// The SDK sends the same request and Auth token either way.
HttpsCallable callableOf(
  FirebaseFunctions functions,
  String name, {
  required HttpsCallableOptions options,
  Uri? server,
}) => server == null
    ? functions.httpsCallable(name, options: options)
    : functions.httpsCallableFromUri(
        server.replace(path: '/$name'),
        options: options,
      );
